// Writes db/castle-tutorial-seed.sql from tutorial-data.js (world rows + quest chain).
// Usage: node scripts/build-castle-tutorial-seed.mjs
import {writeFileSync} from 'node:fs';
import {tutorialEntities,tutorialId,tutorialQuestRows,TUTORIAL_BLUEPRINT} from '../tutorial-data.js';

const literal=value=>{const text=JSON.stringify(value);if(text.includes('$j$'))throw Error('Unexpected dollar quote');return '$j$'+text+'$j$::jsonb'};
export function buildSeed(){
 const entityRows=Object.entries(tutorialEntities).map(([key,d])=>`  ('${tutorialId(key)}',${literal({...d,blueprint:TUTORIAL_BLUEPRINT,blueprintKey:String(key)})})`);
 const questRows=tutorialQuestRows().map(q=>`  ('${q.id}',${literal(q.data)})`);
 return `-- Generated by scripts/build-castle-tutorial-seed.mjs from tutorial-data.js. Do not edit by hand.
-- Castle training grounds (King, tutors, training yard, copse, pond, ore rocks) and the
-- tutorial quest chain. Apply after db/castle-tutorial.sql. Idempotent and safe to re-run.

-- Resolves '@castle:<key>' and '@tutorial:<key>' references to world entity ids.
create or replace function eldervale_private.tutorial_resolve(d jsonb) returns jsonb language plpgsql stable set search_path='' as $$
declare t text:=d::text;m text[];ref text;
begin
 for m in select regexp_matches(t,'"@(castle|tutorial):([0-9]+)"','g') loop
  select e.id::text into ref from eldervale_private.entities e where not e.deleted and e.data->>'blueprint'=(case m[1] when 'castle' then 'eldervale-castle-v1' else '${TUTORIAL_BLUEPRINT}' end) and e.data->>'blueprintKey'=m[2] order by e.created_at limit 1;
  if ref is null then raise exception 'Missing castle reference @%:%',m[1],m[2];end if;
  t:=replace(t,'"@'||m[1]||':'||m[2]||'"','"'||ref||'"');
 end loop;
 return t::jsonb;
end $$;
revoke all on function eldervale_private.tutorial_resolve(jsonb) from public,anon,authenticated;

update eldervale_private.settings set revision=revision+1 where id;
insert into eldervale_private.entities(id,revision,data)
 select v.id::uuid,(select revision from eldervale_private.settings where id),v.data from (values
${entityRows.join(',\n')}
 ) v(id,data)
 on conflict(id) do update set data=excluded.data,revision=excluded.revision,deleted=false
 where eldervale_private.entities.data is distinct from excluded.data or eldervale_private.entities.deleted;

-- Royal Archivist Iven moves aside so the King can hold court in front of the high table
-- (only when he still stands on his original blueprint spot).
update eldervale_private.entities set data=data||'{"x":-335.5,"z":-326.5}'::jsonb,revision=(select revision from eldervale_private.settings where id)
 where data->>'blueprint'='eldervale-castle-v1' and data->>'blueprintKey'='59' and (data->>'x')::float8=-340 and (data->>'z')::float8=-332;

-- Quest chain (version only rises when the definition actually changes).
insert into eldervale_private.quest_definitions(id,data)
 select v.id::uuid,eldervale_private.tutorial_resolve(v.data) from (values
${questRows.join(',\n')}
 ) v(id,data)
 on conflict(id) do update set data=excluded.data,version=eldervale_private.quest_definitions.version+1,updated_at=now()
 where eldervale_private.quest_definitions.data is distinct from excluded.data;
`;
}
if(import.meta.url===`file://${process.argv[1]}`){writeFileSync(new URL('../db/castle-tutorial-seed.sql',import.meta.url),buildSeed());console.log('Wrote db/castle-tutorial-seed.sql')}
