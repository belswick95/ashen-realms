// Writes db/outfit-catalog.sql: server catalog rows for every outfit item in
// outfits.js (plus the cape), and the equip rule for one item per slot.
// usage: node scripts/build-outfit-catalog.mjs
import fs from 'node:fs';
import {armorCatalog} from '../melee-stats.js';
const q=s=>"'"+String(s).replace(/'/g,"''")+"'";
const json=o=>q(JSON.stringify(o))+'::jsonb';
const rows=[];
for(const [key,a] of Object.entries(armorCatalog)){
 rows.push(`(${q('item:armor:'+key)},${json({name:key==='cape'?'Crimson cape':a.name,buy:a.buy,sell:a.sell,field:'armorOwned',key,slot:a.equipSlot})})`);
 rows.push(`(${q('armor:'+key)},${json({name:a.name,desc:a.desc,slot:a.slot,defence:a.defence,reduction:a.reduction})})`);
}
// The exact armour branch of the live equip command, and its replacement.
const OLD="if field='armorOwned' then if slot<>key then raise exception 'Wrong equipment slot';end if;s.equipment:=s.equipment||jsonb_build_object(key,not coalesce((s.equipment->>key)::boolean,false));";
const NEW="if field='armorOwned' then if coalesce(c->>'slot',key)<>slot then raise exception 'Wrong equipment slot';end if;if not coalesce((s.equipment->>key)::boolean,false) then s.equipment:=s.equipment||coalesce((select jsonb_object_agg(e.k,false) from jsonb_each_text(s.equipment) e(k,v) join eldervale_private.realm_catalog r on r.id='item:armor:'||e.k where e.v='true' and e.k<>key and coalesce(r.data->>'slot',e.k)=slot),'{}'::jsonb);end if;s.equipment:=s.equipment||jsonb_build_object(key,not coalesce((s.equipment->>key)::boolean,false));";
const sql=`-- Outfit armour: catalog rows for the ${Object.keys(armorCatalog).length} wearable items (outfits.js + cape)
-- and one worn item per equipment slot. Generated by scripts/build-outfit-catalog.mjs.
--
-- * item:armor:<key>  shop/inventory row; "slot" is the machine slot (helm, chest, ...).
-- * armor:<key>       combat row summed for defence and damage absorption.
--   Bank-note rows are created by the existing catalog trigger.
-- * equip: armour must be equipped into its catalog slot (legacy keys fall back to
--   slot = key, as before), and wearing an item takes off other armour in that slot.
--   Applied as a guarded edit: aborts unless the function is exactly the reviewed version.
begin;

insert into eldervale_private.realm_catalog(id,data) values
${rows.join(',\n')}
on conflict (id) do update set data=excluded.data;

do $migration$
declare
 def text;
 old_branch constant text := ${q(OLD)};
 new_branch constant text := ${q(NEW)};
begin
 select pg_get_functiondef(p.oid) into def from pg_proc p join pg_namespace n on n.oid=p.pronamespace
  where n.nspname='eldervale_private' and p.proname='realm_request_base';
 if md5(def)<>'9ad5c5971cee14acb225a85f1f33e5b4' then raise exception 'realm_request_base changed since this migration was reviewed'; end if;
 if (length(def)-length(replace(def,old_branch,'')))/length(old_branch)<>1 then raise exception 'equip armour branch not found exactly once'; end if;
 execute replace(def,old_branch,new_branch);
end
$migration$;

commit;
`;
fs.writeFileSync(new URL('../db/outfit-catalog.sql',import.meta.url),sql);
console.log('db/outfit-catalog.sql: '+rows.length+' catalog rows');
