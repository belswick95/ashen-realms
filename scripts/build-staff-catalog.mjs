// Writes db/staffs.sql: catalog rows for the magic staffs in weapons.js and
// shop stock for them. Staffs use the existing ranged combat rules (ranged,
// reach); "magic" only changes the client visuals.
// usage: node scripts/build-staff-catalog.mjs
import fs from 'node:fs';import {weaponCatalog} from '../weapons.js';
const q=s=>"'"+String(s).replace(/'/g,"''")+"'";const rows=[];
for(const [key,w] of Object.entries(weaponCatalog))if(w.magic){
 rows.push(['item:weapon:'+key,{name:w.name,buy:w.buy,sell:w.sell,field:'weaponsOwned',key}]);
 rows.push(['weapon:'+key,{name:w.name,desc:w.desc,kind:w.kind,damage:w.damage,attack:w.attack,speed:w.speed,reach:w.reach,twoHanded:true,ranged:true,magic:true}]);
}
// Each gear merchant sells one staff; the castle quartermaster the finest two.
const STOCK=[['9c32d3de-8fee-4e11-af51-9bc84d7fbb46','apprenticeStaff'],['4b178de6-0fcb-47d4-9587-40cb9254745e','amethystStaff'],['f2365884-03c8-43b6-aa2d-8df745319bbe','emberStaff'],['36b9aa48-81f4-44bf-b934-dbc4ec8f1a08','sapphireStaff'],['36b9aa48-81f4-44bf-b934-dbc4ec8f1a08','emberStaff']];
fs.writeFileSync(new URL('../db/staffs.sql',import.meta.url),`-- Magic staffs (Magic Staff Set by AnyRPG, CC0). Generated by scripts/build-staff-catalog.mjs.
-- Ranged like bows (server rules in db/weapons-and-archery.sql); apply with the client release.
insert into eldervale_private.realm_catalog(id,data)
select r->>0,r->1 from jsonb_array_elements(${q(JSON.stringify(rows))}::jsonb) r
on conflict (id) do update set data=excluded.data;
insert into eldervale_private.shop_stock(merchant,item,buy,sell,stock,target_stock)
select s.merchant::uuid,s.item,(c.data->>'buy')::int,(c.data->>'sell')::int,-1,null
from (values ${STOCK.map(([m,k])=>`(${q(m)},${q('weapon:'+k)})`).join(',')}) s(merchant,item) join eldervale_private.realm_catalog c on c.id='item:'||s.item
on conflict (merchant,item) do update set buy=excluded.buy,sell=excluded.sell,stock=-1,target_stock=null;
`);console.log('db/staffs.sql',rows.length,'rows');
