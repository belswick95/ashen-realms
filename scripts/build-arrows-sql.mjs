// Writes db/arrows.sql: the Arrows ammunition item, world_tick rules (bows use
// one arrow per shot; with none the archer's turn passes), and shop stock.
// usage: node scripts/build-arrows-sql.mjs
import fs from 'node:fs';
const q=s=>"'"+String(s).replace(/'/g,"''")+"'";
// Ammunition is the existing fletching product 'arrows' (Iron arrows). Outfitters
// sell it cheaply (a shot must cost less than a kill pays) and buy none back.
const BUY=1,SELL=0;
const bow="coalesce((w->>'ranged')::boolean,false) and not coalesce((w->>'magic')::boolean,false)";
const EDITS=[
 // An archer only keeps shooting while a monster closes if they have arrows.
 ['world_tick',"shooting:=coalesce((w->>'ranged')::boolean,false) and dist<=coalesce((w->>'reach')::float8,0);",
  "shooting:=coalesce((w->>'ranged')::boolean,false) and dist<=coalesce((w->>'reach')::float8,0) and (coalesce((w->>'magic')::boolean,false) or coalesce((victim.stats->>'arrows')::integer,0)>0);"],
 // Out of arrows: the archer's turn passes (the fight continues; a bow is no escape).
 ['world_tick',"   if a.phase='ready' then\n",
  `   if a.phase='ready' and a.turn='player' and ${bow} and coalesce((victim.stats->>'arrows')::integer,0)<1 then\n    update eldervale_private.realm_actors set phase='recover',due_at=t+interval '1.2 seconds',turn_at=t where id=a.id;\n    perform eldervale_private.emit(jsonb_build_object('type','notice','player',a.target,'text','You are out of arrows. Outfitters sell them.'));\n   elsif a.phase='ready' then\n`],
 // Each shot that lands (hit or blocked) uses one arrow.
 ['world_tick',"     update eldervale_private.realm_actors set hp=greatest(0,hp-damage),phase='recover',due_at=greatest(t+interval '.75 seconds',a.turn_at) where id=a.id;",
  `     update eldervale_private.realm_actors set hp=greatest(0,hp-damage),phase='recover',due_at=greatest(t+interval '.75 seconds',a.turn_at) where id=a.id;\n     if ${bow} then update public.player_saves set stats=stats||jsonb_build_object('arrows',greatest(0,coalesce((stats->>'arrows')::integer,0)-1)) where user_id=a.target;end if;`]
];
const OUTFITTERS=['9c32d3de-8fee-4e11-af51-9bc84d7fbb46','4b178de6-0fcb-47d4-9587-40cb9254745e','f2365884-03c8-43b6-aa2d-8df745319bbe','36b9aa48-81f4-44bf-b934-dbc4ec8f1a08'];
fs.writeFileSync(new URL('../db/arrows.sql',import.meta.url),`-- Arrows: the fletching product 'arrows' (Iron arrows, player_saves.stats.arrows)
-- is now bow ammunition, one used per shot; outfitters sell it at ${BUY} gold.
-- Without arrows an archer's turn passes with a notice. Staffs need none.
-- Generated by scripts/build-arrows-sql.mjs. Apply with the client release.
-- Each function edit must match its exact text once, or the migration aborts.
insert into eldervale_private.shop_stock(merchant,item,buy,sell,stock,target_stock)
select m::uuid,'arrows',${BUY},${SELL},-1,null from unnest(array[${OUTFITTERS.map(q).join(',')}]) m
on conflict (merchant,item) do update set buy=excluded.buy,sell=excluded.sell,stock=-1,target_stock=null;
do $migration$
declare edits jsonb := ${q(JSON.stringify(EDITS))}; e jsonb; def text;
begin
 select pg_get_functiondef('eldervale_private.world_tick'::regproc) into def;
 for e in select x from jsonb_array_elements(edits) x loop
  if (length(def)-length(replace(def,e->>1,'')))/length(e->>1)<>1 then raise exception 'Edit does not match exactly once: %',left(e->>1,80); end if;
  def:=replace(def,e->>1,e->>2);
 end loop;
 execute def;
end
$migration$;
`);console.log('db/arrows.sql written');
