// Writes skill-guide-sql-data.js: the skill-guide numbers that live only in the server SQL.
// Woodcutting has no client table: the tree levels are in eldervale_private.gathering_error
// (db/osrs-skill-parity.sql, first defined in db/professions-engine.sql), the XP per log in tree_log_xp_osrs and the chop chances per axe in
// woodcut_chance (db/osrs-skill-parity.sql). tests/skill-guide.test.js re-parses the SQL and checks
// the module still matches it.
//   node scripts/build-skill-guide-data.mjs
import fs from 'node:fs';
import {fileURLToPath} from 'node:url';

const root=new URL('../',import.meta.url);
export const SQL_SOURCES={engine:'db/professions-engine.sql',parity:'db/osrs-skill-parity.sql'};
// "case d->>'logItem' when 'oakLogs' then 15 ... else 1 end" -> {oakLogs:15,...,wood:1}
function caseTable(expr,label){
 const m=/case\s+\w+(?:\.\w+)?->>'logItem'\s+((?:when\s+'\w+'\s+then\s+[\d.]+\s*)+)else\s+([\d.]+)\s+end/.exec(expr);
 if(!m)throw Error('No logItem case table for '+label);
 const out={wood:Number(m[2])};for(const [,k,v] of m[1].matchAll(/when\s+'(\w+)'\s+then\s+([\d.]+)/g))out[k]=Number(v);return out;
}
// The body of the last definition of a function (later files and patches win).
const fnBody=(sql,name)=>{const defs=[...sql.matchAll(new RegExp('create\\s+(?:or\\s+replace\\s+)?function\\s+eldervale_private\\.'+name+'\\(','g'))];if(!defs.length)throw Error('Missing function '+name);const i=defs[defs.length-1].index;const end=sql.indexOf('$$;',sql.indexOf('$$',i)+2);return sql.slice(i,end)};
// The woodcutting table from the two SQL files' text.
export function parseWoodcuttingSql(engineSql,paritySql){
 // The level gate: osrs-skill-parity.sql redefines gathering_error after professions-engine.sql (it wins).
 const hasGate=sql=>/create\s+(?:or\s+replace\s+)?function\s+eldervale_private\.gathering_error\(/.test(sql)&&fnBody(sql,'gathering_error').includes("method='woodcut'");
 const gate=fnBody(hasGate(paritySql)?paritySql:engineSql,'gathering_error'),woodcut=gate.slice(gate.indexOf("method='woodcut'"));
 const levels=caseTable(woodcut.replace(/o\.data/g,'d'),'tree levels');
 const xp=caseTable(fnBody(paritySql,'tree_log_xp_osrs'),'tree XP');
 const chance=fnBody(paritySql,'woodcut_chance'),cols={};
 for(const [,expr,col] of chance.matchAll(/(case\s+d->>'logItem'[^]*?end)\s+(bl|bh|il|ih)\b/g))cols[col]=caseTable(expr,'chop chance '+col);
 for(const c of ['bl','bh','il','ih'])if(!cols[c])throw Error('Missing chop chance column '+c);
 // The iron-axe test ("weaponsOwned ? 'axe'") and the axes the woodcut gate accepts (osrs-skill-parity patch).
 const iron=/\?'(\w+)'\s+or\s+s\.equipment->>'weapon'='\1'\s+iron/.exec(chance)?.[1];
 const any=/\?\|\s*array\[([^\]]+)\]/.exec(paritySql)?.[1];
 if(!iron||!any)throw Error('Missing axe checks');
 const axes=[...any.matchAll(/'(\w+)'/g)].map(m=>m[1]);
 const logs=Object.keys(levels).sort((a,b)=>levels[a]-levels[b]||a.localeCompare(b));
 return {
  trees:logs.map(log=>({log,level:levels[log],xp:xp[log]??xp.wood,bronze:[cols.bl[log]??cols.bl.wood,cols.bh[log]??cols.bh.wood],iron:[cols.il[log]??cols.il.wood,cols.ih[log]??cols.ih.wood]})),
  axes:axes.map(id=>({weapon:id,chances:id===iron?'iron':'bronze'}))
 };
}
export function readWoodcutting(){const read=f=>fs.readFileSync(new URL(f,root),'utf8');return parseWoodcuttingSql(read(SQL_SOURCES.engine),read(SQL_SOURCES.parity))}
export function moduleSource(data=readWoodcutting()){
 return `// GENERATED by scripts/build-skill-guide-data.mjs from ${SQL_SOURCES.parity} (gathering_error, tree_log_xp_osrs,
// woodcut_chance; ${SQL_SOURCES.engine} is the fallback for gathering_error). Do not edit: change the SQL and re-run the script.
// Woodcutting per log: the level, XP per log, and the OSRS-style chop chance out of 256 at Woodcutting
// 1 and 99 with a bronze-tier and an iron-tier axe. axes: the axes the server accepts and which column they use.
export const WOODCUTTING_TREES=${JSON.stringify(data.trees)};
export const WOODCUTTING_AXES=${JSON.stringify(data.axes)};
`;
}
if(process.argv[1]===fileURLToPath(import.meta.url)){fs.writeFileSync(new URL('skill-guide-sql-data.js',root),moduleSource());console.log('wrote skill-guide-sql-data.js')}
