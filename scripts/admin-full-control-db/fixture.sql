CREATE OR REPLACE FUNCTION eldervale_private.combat_xp(uid uuid, damage integer, style text, w jsonb)
 RETURNS void LANGUAGE plpgsql SET search_path TO ''
AS $function$
declare d integer:=greatest(0,coalesce(damage,0));magic boolean:=coalesce((w->>'magic')::boolean,false);ranged boolean:=coalesce((w->>'ranged')::boolean,false);share numeric;gains jsonb;
begin
 share:=round(1.33*d,2);
 gains:=(case when magic then jsonb_build_object('magicXP',2*d+coalesce((w->>'spellXp')::numeric,5.5))
  when ranged then jsonb_build_object('rangedXP',4*d)
  when style='stab' then jsonb_build_object('attackXP',4*d)
  when style='lunge' then jsonb_build_object('attackXP',share,'strengthXP',share,'defenceXP',share)
  else jsonb_build_object('strengthXP',4*d) end)||jsonb_build_object('hitpointsXP',share);
 update public.player_saves set skills=skills||coalesce((select jsonb_object_agg(g.key,trim_scale(least(200000000,round(coalesce((skills->>g.key)::numeric,0)+g.value::numeric,2)))) from jsonb_each_text(gains) g where g.value::numeric>0),'{}'::jsonb) where user_id=uid;
end $function$;

CREATE OR REPLACE FUNCTION eldervale_private.actor_loot(actor_id text, killer uuid)
 RETURNS void LANGUAGE plpgsql SECURITY DEFINER SET search_path TO ''
AS $function$
declare a eldervale_private.realm_actors;l jsonb;c jsonb;lo integer;hi integer;n integer;
begin
 select * into a from eldervale_private.realm_actors where id=actor_id;
 if a.id is null or killer is null or jsonb_typeof(a.data->'loot') is distinct from 'array' then return;end if;
 if (select count(*) from eldervale_private.ground_drops where owner_id=killer)>=100 then return;end if;
 for l in select value from jsonb_array_elements(a.data->'loot') with ordinality e(value,o) where o<=8 loop
  begin
   if random()>least(1,greatest(0,coalesce((l->>'chance')::float8,1))) then continue;end if;
   select data into c from eldervale_private.realm_catalog where id='item:'||(l->>'item');
   if c is null or c?'noteOf' then continue;end if;
   lo:=least(1000,greatest(1,coalesce((l->>'min')::integer,1)));hi:=least(1000,greatest(lo,coalesce((l->>'max')::integer,lo)));
   n:=case when c?'field' then 1 else lo+floor(random()*(hi-lo+1))::integer end;
   insert into eldervale_private.ground_drops(owner_id,item,amount,x,z,floor) values(killer,l->>'item',n,a.x+(random()-.5)*1.4,a.z+(random()-.5)*1.4,coalesce((a.data->>'floor')::integer,0));
  exception when others then raise warning 'Loot row skipped for %: %',actor_id,sqlerrm;
  end;
 end loop;
end $function$;

CREATE OR REPLACE FUNCTION eldervale_private.merchant_quote(base_buy integer, base_sell integer, available integer, target integer, purchase boolean, amount integer DEFAULT 1)
 RETURNS integer LANGUAGE plpgsql IMMUTABLE SET search_path TO ''
AS $function$
declare total bigint:=0;unit_buy integer;unit_sell integer;factor numeric;i integer;
begin
 if base_buy<1 or base_sell<0 or amount not between 1 and 10 then raise exception 'Invalid merchant quote';end if;
 for i in 0..amount-1 loop
  factor:=case when available<0 then 1 else greatest(.65,least(1.50,1+(greatest(10,coalesce(target,10))-(available-case when purchase then i else -1 end))::numeric/greatest(10,coalesce(target,10))*.35)) end;
  unit_buy:=greatest(1,ceil(base_buy*factor)::integer);
  unit_sell:=least(floor(base_sell*factor)::integer,greatest(0,floor(unit_buy*.75)::integer));
  total:=total+case when purchase then unit_buy else unit_sell end;
 end loop;
 return total::integer;
end $function$;

CREATE OR REPLACE FUNCTION eldervale_private.item_quantity(uid uuid, item text)
 RETURNS integer LANGUAGE sql STABLE SET search_path TO ''
AS $function$
 select case when item='gold' then s.gold when c.data?'field' then (select count(*)::integer from jsonb_array_elements_text(coalesce(s.inventory->(c.data->>'field'),'[]'))v where v.value=c.data->>'key') else coalesce((s.stats->>item)::integer,0) end from public.player_saves s left join eldervale_private.realm_catalog c on c.id='item:'||item where s.user_id=uid
$function$;
CREATE OR REPLACE FUNCTION eldervale_private.equipment_reserved(uid uuid, c jsonb)
 RETURNS integer LANGUAGE sql STABLE SET search_path TO ''
