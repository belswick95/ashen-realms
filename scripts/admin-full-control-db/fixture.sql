CREATE OR REPLACE FUNCTION eldervale_private.validate_offer(uid uuid, offer jsonb)
 RETURNS void LANGUAGE plpgsql SET search_path TO ''
AS $function$declare k text;n numeric;c jsonb;begin
 if jsonb_typeof(offer)<>'object' or jsonb_typeof(offer->'items')<>'object' or (select count(*) from jsonb_object_keys(offer->'items'))>eldervale_private.inventory_capacity() then raise exception 'Invalid trade offer';end if;
 n:=(offer->>'gold')::numeric;if n is null or n::text in ('NaN','Infinity','-Infinity') or n<>trunc(n) or n<0 or n>1000000000 or n>eldervale_private.item_quantity(uid,'gold') then raise exception 'Not enough gold';end if;
 for k,c in select key,value from jsonb_each(offer->'items') loop
  n:=c::text::numeric;if k='gold' or not exists(select 1 from eldervale_private.realm_catalog where id='item:'||k) or n::text in ('NaN','Infinity','-Infinity') or n<>trunc(n) or n<1 or n>1000000 or n>eldervale_private.item_quantity(uid,k) or eldervale_private.item_worn(uid,k) then raise exception 'Unavailable or equipped trade item: %',k;end if;
 end loop;
end $function$;

CREATE OR REPLACE FUNCTION eldervale_private.item_change(uid uuid, item text, amount integer, bank boolean DEFAULT false)
 RETURNS void LANGUAGE plpgsql SET search_path TO ''
AS $function$
declare s public.player_saves;c jsonb;f text;k text;n integer;vals jsonb;result jsonb;v text;removed integer:=0;reserved integer;
begin
 select * into s from public.player_saves where user_id=uid for update;
 if s.user_id is null then raise exception 'Character not found';end if;
 if item='gold' then if s.gold+amount<0 or s.gold::bigint+amount>1000000000 then raise exception 'Gold amount outside limits';end if;update public.player_saves set gold=gold+amount where user_id=uid;return;end if;
 select data into c from eldervale_private.realm_catalog where id='item:'||item;if c is null then raise exception 'Unknown item';end if;
 if bank and c?'noteOf' then perform eldervale_private.item_change(uid,c->>'noteOf',amount,true);return;end if;
 f:=c->>'field';k:=c->>'key';
 if bank then
  n:=coalesce((s.inventory->'bank'->>item)::integer,0)+amount;if n<0 or n>1000000000 then raise exception 'Bank quantity outside limits';end if;
  s.inventory:=jsonb_set(s.inventory,'{bank}',coalesce(s.inventory->'bank','{}')||jsonb_build_object(item,n));
 elsif f is null then
  n:=coalesce((s.stats->>item)::integer,0)+amount;if n<0 or n>1000000000 then raise exception 'Not enough items or stack limit reached';end if;s.stats:=s.stats||jsonb_build_object(item,n);
 else
  vals:=coalesce(s.inventory->f,'[]');n:=eldervale_private.item_quantity(uid,item);reserved:=eldervale_private.equipment_reserved(uid,c);
  if amount>0 then
   if amount>eldervale_private.inventory_capacity() then raise exception 'Carried equipment uses one slot per copy';end if;
   vals:=vals||(select coalesce(jsonb_agg(k),'[]') from generate_series(1,amount));
  elsif amount<0 then
   if n+amount<reserved then raise exception 'Not enough unequipped copies. Unequip the last copy first';end if;
   result:='[]';for v in select jsonb_array_elements_text(vals) loop if v=k and removed< -amount then removed:=removed+1;else result:=result||jsonb_build_array(v);end if;end loop;vals:=result;
  end if;
  s.inventory:=s.inventory||jsonb_build_object(f,vals);
 end if;
 update public.player_saves set stats=s.stats,inventory=s.inventory where user_id=uid;
end $function$;

CREATE OR REPLACE FUNCTION eldervale_private.console_check_entity(d jsonb)
 RETURNS void LANGUAGE plpgsql STABLE SET search_path TO ''
AS $function$
declare r jsonb;k text;n numeric;
begin
 if d is null or jsonb_typeof(d)<>'object' then return;end if;
 if d?'loot' and jsonb_typeof(d->'loot')<>'null' then
  if jsonb_typeof(d->'loot')<>'array' or jsonb_array_length(d->'loot')>8 then raise exception 'Loot needs up to eight rows';end if;
  for r in select value from jsonb_array_elements(d->'loot') loop
   if jsonb_typeof(r)<>'object' or not exists(select 1 from eldervale_private.realm_catalog c where c.id='item:'||(r->>'item') and not c.data?'noteOf') then raise exception 'Unknown loot item: %',r->>'item';end if;
   if coalesce((r->>'min')::numeric,0) not between 1 and 1000 or coalesce((r->>'max')::numeric,0) not between (r->>'min')::numeric and 1000 or coalesce((r->>'chance')::numeric,0)<=0 or (r->>'chance')::numeric>1 then raise exception 'Loot quantities must be 1–1000 and chance above 0 up to 1';end if;
  end loop;
 end if;
 foreach k in array array['xpReward','goldReward'] loop
  if d?k and jsonb_typeof(d->k)<>'null' then n:=(d->>k)::numeric;if n<>trunc(n) or n<0 or n>(case when k='xpReward' then 100000 else 1000000 end) then raise exception 'Invalid %',k;end if;end if;
 end loop;
end $function$;

