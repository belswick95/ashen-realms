-- gathering_tick: the live body, trimmed to the woodcutting branch that carries the patch anchor.
CREATE OR REPLACE FUNCTION eldervale_private.gathering_tick(t timestamp with time zone)
 RETURNS void LANGUAGE plpgsql SECURITY DEFINER SET search_path TO ''
AS $function$
declare a eldervale_private.gathering_actions;o eldervale_private.realm_objects;n integer;
begin
 for a in select * from eldervale_private.gathering_actions where due_at<=t for update loop
  select * into o from eldervale_private.realm_objects where id=a.target for update;
  if a.method='woodcut' then
   n:=1;
   perform eldervale_private.item_change(a.user_id,eldervale_private.tree_log_item(o.data),n);
   update public.player_saves set stats=stats||jsonb_build_object('woodXP',trim_scale(least(200000000,coalesce((stats->>'woodXP')::numeric,0)+eldervale_private.tree_log_xp_osrs(o.data)*n))) where user_id=a.user_id;
  end if;
  update eldervale_private.gathering_actions set started_at=t,due_at=t+make_interval(secs=>3) where user_id=a.user_id;
 end loop;
end $function$;
