// Writes db/quest-arc-*.sql from scripts/quest-arcs/<arc>.mjs (the four Round-3 story arcs).
// usage: node --import ./tests/helpers/preload.js scripts/quest-arcs/build.mjs
// Apply order: db/quests-v2.sql, (R3-I db/bosses-*.sql for the reserved reward items), then
// db/quest-arc-0-core.sql and every db/quest-arc-<n>-<arc>-<part>.sql in file-name order.
import fs from 'node:fs';
import {resolver,questRow,BLUEPRINT,ARC_CODES} from './common.mjs';
import * as crown from './crown.mjs';
import * as frontier from './frontier.mjs';
import * as forge from './forge.mjs';
import * as tide from './tide.mjs';

export const ARCS=[crown,frontier,forge,tide];
export const MAX_FILE=40*1024;
const root=new URL('../../',import.meta.url);
const json=(v,tag='j')=>{const t=JSON.stringify(v);if(t.includes('$'+tag+'$'))throw Error('quote clash');return '$'+tag+'$'+t+'$'+tag+'$'};
export const entitiesOf=a=>[...a.npcs,...a.monsters,...(a.objects||[])];
export function questRows(a){const r=resolver(entitiesOf(a));return a.quests.map(q=>questRow(a.arc.key,q,r))}
export const allKeys=()=>Object.keys(ARC_CODES).flatMap(a=>[1,2,3,4,5].map(i=>`arc-${a}-${i}`));

const header=(title,lines)=>`-- ${title}\n-- Generated by scripts/quest-arcs/build.mjs from scripts/quest-arcs/*.mjs. Do not edit by hand.\n${lines.map(l=>'-- '+l).join('\n')}\nbegin;\nset local lock_timeout='5s';\n`;

function core(){
 const areas=ARCS.flatMap(a=>a.areas||[]);
 return header('Quest arcs (Round 3, R3-J): shared helpers, quest gates on passages and shortcuts, story arenas.',[
  'Apply after db/quests-v2.sql and the underground files (db/underground-1-engine.sql ... -3-console.sql),',
  'then db/quest-arc-1-* ... -4-* in file-name order. Idempotent; safe on a running game.',
  '* quest_arc_keys(): every arc quest key (a quest may require an arc quest from a file applied later).',
  '* quest_arc_put(id,data): validates with quest_v2_check and stores the quest; a row the owner has',
  '  edited in the Game console (version > 1) is never overwritten. Reward items another round has not',
  '  shipped yet are left out with a notice (re-run the arc file once they exist).',
  '* quest_arc_entities(rows): NPCs, monsters and shortcuts with fixed ids (blueprint '+BLUEPRINT+');',
  '  owner-edited (data.ownerEdited) or owner-deleted rows are kept as they are.',
  '* Passage and shortcut gates (underground_command, patched once; skipped if already gated):',
  '  data.passage.requires.unlock / data.agility.requires.unlock = a quest unlock id the player must hold',
  '  (player_unlocked), requires.quest = a quest key the player must have completed.',
  '* Story arenas (underground areas) for the arc finales: '+areas.map(a=>a.id).join(', ')+'.',
  '  An area the owner saved from the console (updated_by set) keeps its definition.'])+`
create or replace function eldervale_private.quest_arc_keys() returns text[] language sql immutable set search_path='' as $$
 select ${"array["+allKeys().map(k=>"'"+k+"'").join(',')+"]"}
$$;

create or replace function eldervale_private.quest_arc_put(qid uuid, d jsonb) returns text language plpgsql set search_path='' as $fn$
declare k text;later text[]:='{}';chk jsonb;kept jsonb;
begin
 if jsonb_typeof(d->'items')='object' then
  select coalesce(jsonb_object_agg(e.key,e.value),'{}'::jsonb) into kept from jsonb_each(d->'items') e where exists(select 1 from eldervale_private.realm_catalog c where c.id='item:'||e.key);
  if kept<>d->'items' then raise notice 'Quest %: reward items not in the catalog yet were left out: %',d->>'key',(select string_agg(e.key,', ') from jsonb_each(d->'items') e where not kept?e.key);d:=d||jsonb_build_object('items',kept);end if;
 end if;
 for k in select jsonb_array_elements_text(coalesce(d->'requirements'->'quests','[]'::jsonb)) loop
  if not exists(select 1 from eldervale_private.quest_definitions q where q.data->>'key'=k and q.id<>qid) then
   if not (k=any(eldervale_private.quest_arc_keys())) then raise exception 'Quest %: required quest % does not exist',d->>'key',k;end if;
   later:=later||k;
  end if;
 end loop;
 chk:=d;
 if cardinality(later)>0 then chk:=jsonb_set(d,'{requirements,quests}',(select coalesce(jsonb_agg(x),'[]'::jsonb) from jsonb_array_elements_text(d->'requirements'->'quests') x where not (x=any(later))));end if;
 perform eldervale_private.quest_v2_check(chk,qid);
 insert into eldervale_private.quest_definitions(id,data) values(qid,d)
  on conflict(id) do update set data=excluded.data,updated_at=now() where eldervale_private.quest_definitions.version=1 and eldervale_private.quest_definitions.data is distinct from excluded.data;
 return d->>'key'||(case when cardinality(later)>0 then ' (needs '||array_to_string(later,', ')||' from a later file)' else '' end);
end $fn$;

create or replace function eldervale_private.quest_arc_entities(rows jsonb) returns integer language plpgsql set search_path='' as $fn$
declare rev bigint;k integer;
begin
 if not exists(select 1 from jsonb_array_elements(rows) r where not exists(select 1 from eldervale_private.entities e where e.id=(r->>'id')::uuid and (e.data=(r->'data') or e.deleted or coalesce((e.data->>'ownerEdited')::boolean,false)))) then return 0;end if;
 update eldervale_private.settings set revision=revision+1 where id returning revision into rev;
 insert into eldervale_private.entities(id,revision,data) select (r->>'id')::uuid,rev,r->'data' from jsonb_array_elements(rows) r
  on conflict(id) do update set data=excluded.data,revision=excluded.revision
  where not eldervale_private.entities.deleted and not coalesce((eldervale_private.entities.data->>'ownerEdited')::boolean,false) and eldervale_private.entities.data is distinct from excluded.data;
 get diagnostics k=row_count;return k;
end $fn$;
revoke all on function eldervale_private.quest_arc_keys(),eldervale_private.quest_arc_put(uuid,jsonb),eldervale_private.quest_arc_entities(jsonb) from public,anon,authenticated;

-- Quest gates on passages (entrances) and agility shortcuts.
do $gate$
declare fn regprocedure:=to_regprocedure('eldervale_private.underground_command(uuid,text,jsonb,uuid,bigint)');def text;
begin
 if fn is null then raise notice 'Quest arc gates skipped: the underground engine is not installed';return;end if;
 def:=pg_get_functiondef(fn);
 if position('quest-arc-gate' in def)>0 then return;end if;
 begin
  perform eldervale_private.patch_function(fn,array[
$a$   if not coalesce((select a.enabled from eldervale_private.underground_areas a where a.id=d->>'area'),false) then raise exception 'The way is blocked for now.';end if;
$a$,
$b$   if not coalesce((select a.enabled from eldervale_private.underground_areas a where a.id=d->>'area'),false) then raise exception 'The way is blocked for now.';end if;
   /*quest-arc-gate*/ if coalesce(d->'requires'->>'unlock','')<>'' and not eldervale_private.player_unlocked(auth.uid(),d->'requires'->>'unlock') then raise exception '%',coalesce(d->'requires'->>'lockedText','Something bars the way. Perhaps a quest will open it.');end if;
   if coalesce(d->'requires'->>'quest','')<>'' and not eldervale_private.quest_done_key(auth.uid(),d->'requires'->>'quest') then raise exception '%',coalesce(d->'requires'->>'lockedText','Something bars the way. Perhaps a quest will open it.');end if;
$b$,
$a$   need:=greatest(1,coalesce((d->>'level')::integer,1));lvl:=eldervale_private.skill_level(auth.uid(),'agility');
$a$,
$b$   /*quest-arc-gate*/ if coalesce(d->'requires'->>'unlock','')<>'' and not eldervale_private.player_unlocked(auth.uid(),d->'requires'->>'unlock') then raise exception '%',coalesce(d->'requires'->>'lockedText','You do not know this way yet.');end if;
   need:=greatest(1,coalesce((d->>'level')::integer,1));lvl:=eldervale_private.skill_level(auth.uid(),'agility');
$b$]);
 exception when raise_exception then raise notice 'Quest arc gates not added (the underground command was changed elsewhere): %',sqlerrm;
 end;
end $gate$;

-- Story arenas.
do $areas$
declare a jsonb;
begin
 if to_regclass('eldervale_private.underground_areas') is null then raise notice 'Quest arc arenas skipped: the underground engine is not installed';return;end if;
 for a in select value from jsonb_array_elements(${json(areas)}::jsonb) loop
  insert into eldervale_private.underground_areas(id,data,enabled) values(a->>'id',a-'enabled',coalesce((a->>'enabled')::boolean,true))
   on conflict(id) do update set data=excluded.data,updated_at=now() where eldervale_private.underground_areas.updated_by is null and eldervale_private.underground_areas.data is distinct from excluded.data;
  perform eldervale_private.underground_sync(a->>'id');
 end loop;
end $areas$;

commit;
`;
}

function arcFiles(a,index){
 const key=a.arc.key,rows=questRows(a),ents=entitiesOf(a);
 const top=`-- Catalog: quest items and keepsakes (untradeable, kept on death, never sold).
insert into eldervale_private.realm_catalog(id,data) select r->>0,r->1 from jsonb_array_elements(${json(a.items)}::jsonb) r
on conflict(id) do update set data=excluded.data where not coalesce((eldervale_private.realm_catalog.data->>'ownerEdited')::boolean,false) and eldervale_private.realm_catalog.data is distinct from excluded.data;

-- People, monsters and shortcuts of the arc (fixed ids; the entity trigger fills realm_actors / realm_objects).
select eldervale_private.quest_arc_entities(${json(ents.map(e=>({id:e.id,data:e.data})))}::jsonb);
`;
 const put=r=>`select eldervale_private.quest_arc_put('${r.id}',${json(r.data,'q')}::jsonb);\n`;
 const B=t=>Buffer.byteLength(t),parts=[[]];let size=B(top)+3000;
 for(const r of rows){const s=put(r);if(size+B(s)>MAX_FILE-2500&&parts.at(-1).length){parts.push([]);size=3000}parts.at(-1).push(s);size+=B(s)}
 return parts.map((qs,i)=>{
  const name=`db/quest-arc-${index}-${key}-${String.fromCharCode(97+i)}.sql`;
  const names=rows.filter(r=>qs.some(s=>s.includes(r.id))).map(r=>`${r.data.name} (${r.data.key})`);
  const body=header(`Quest arc ${index}: ${a.arc.name} — ${a.arc.region}. Part ${i+1} of ${parts.length}.`,[
   'Apply after db/quest-arc-0-core.sql'+(i?` and db/quest-arc-${index}-${key}-${String.fromCharCode(96+i)}.sql`:'')+'. Idempotent.',
   'Quests: '+names.join('; ')+'.',
   ...(i===0?['Seeds: '+a.items.length+' catalog items, '+a.npcs.length+' NPCs, '+a.monsters.length+' monsters, '+(a.objects||[]).length+' gated shortcut(s).']:[])])
   +(i===0?'\n'+top:'')+'\n-- Quests (validated by quest_v2_check; edit them later in the Game console › Quests).\n'+qs.join('')+'\ncommit;\n';
  return [name,body];
 });
}

export function buildAll(){
 const out=[['db/quest-arc-0-core.sql',core()]];
 ARCS.forEach((a,i)=>{if(a.quests.length)out.push(...arcFiles(a,i+1))});
 return out;
}
if(import.meta.url===`file://${process.argv[1]}`){
 for(const [name,body] of buildAll()){if(Buffer.byteLength(body)>MAX_FILE)throw Error(name+' is '+body.length+' bytes');fs.writeFileSync(new URL(name,root),body);console.log(name,Buffer.byteLength(body))}
}
