// Writes db/skilling-world.sql from skilling-areas.js (see scripts/plan-skilling-areas.mjs).
// usage: node scripts/build-skilling-world-sql.mjs
import fs from 'node:fs';
import {SKILLING_BLUEPRINT,skillingAreas,skillingNodes} from '../skilling-areas.js';
const root=new URL('../',import.meta.url);
// The starter trail's higher-tier rocks predate the Eldervale metal names.
export const LEGACY_NAMES=[['Mithril rocks','Moonsilver rocks'],['Adamantite rocks','Verdite rocks'],['Runite rocks','Tidestone rocks']];
const rows=skillingNodes.map(({id,key,...n})=>JSON.stringify({id,key,...n}));
const sql=`-- Open-world skilling areas: OSRS-style mines and tree groves spread across the overworld by
-- level, plus a furnace at the coal field. Generated by scripts/build-skilling-world-sql.mjs from
-- skilling-areas.js (placed by scripts/plan-skilling-areas.mjs on walkable, dry, level ground away
-- from roads, towns, buildings, water and other objects; tests/skilling-world.test.js).
--
-- Apply after db/professions-world.sql (any later order is fine). Idempotent and owner-safe:
--  * every node has a fixed id; a row that already exists (moved, edited or removed in World
--    Studio, deleted rows included) is never touched again, so owner edits survive a re-run;
--  * nodes go in through eldervale_private.entities, so the entity_runtime trigger creates the
--    realm objects (kind rock / tree / furnace) the gathering engine mines, chops and respawns;
--  * before inserting, each node's spot is checked against the live world (doors, other objects,
--    the walk check); a blocked spot is nudged up to 6 m, or skipped with a notice;
--  * the starter trail's "Mithril / Adamantite / Runite rocks" take their Eldervale names
--    (Moonsilver / Verdite / Tidestone) only while the owner has not renamed them.
-- Areas (centre x, z; nodes):
${skillingAreas.map(a=>'--  '+a.name+' ('+a.x+', '+a.z+'; '+a.count+'): '+a.note).join('\n')}
do $$declare row jsonb;d jsonb;rev bigint;bx float8;bz float8;dx float8;dz float8;ok boolean;i integer;added integer:=0;begin
 perform pg_advisory_xact_lock(736211);
 -- Eldervale names for the starter trail's higher-tier rocks (unchanged owner names only).
 if exists(select 1 from eldervale_private.entities where data->>'blueprint'='professions-v1' and data->>'template'='rock' and data->>'name' in(${LEGACY_NAMES.map(([a])=>"'"+a+"'").join(',')})) then
  update eldervale_private.settings set revision=revision+1 where id returning revision into rev;
  update eldervale_private.entities set revision=rev,data=data||jsonb_build_object('name',case data->>'name' ${LEGACY_NAMES.map(([a,b])=>"when '"+a+"' then '"+b+"'").join(' ')} end)
   where data->>'blueprint'='professions-v1' and data->>'template'='rock' and data->>'name' in(${LEGACY_NAMES.map(([a])=>"'"+a+"'").join(',')});
 end if;
 for row in select value from jsonb_array_elements($j$[
${rows.join(',\n')}
]$j$::jsonb) loop
  -- Placed once: an existing row (even one the owner removed) stays as the owner left it.
  if exists(select 1 from eldervale_private.entities where id=(row->>'id')::uuid or data->>'skillingKey'=row->>'key') then continue;end if;
  bx:=(row->>'x')::float8;bz:=(row->>'z')::float8;ok:=false;
  for i in 0..24 loop
   dx:=bx;dz:=bz;if i>0 then dx:=bx+cos(i*2.4)*(1.5+i*0.19);dz:=bz+sin(i*2.4)*(1.5+i*0.19);end if;
   if exists(select 1 from eldervale_private.realm_objects where kind='door' and sqrt(power(x-dx,2)+power(z-dz,2))<9*coalesce((data->>'scale')::float8,1)) then continue;end if;
   if exists(select 1 from eldervale_private.realm_objects where kind<>'door' and x between dx-3 and dx+3 and z between dz-3 and dz+3 and sqrt(power(x-dx,2)+power(z-dz,2))<(case when kind in('tree','rock') then 3.2 else 2.6 end)) then continue;end if;
   if (select bool_and(eldervale_private.can_step(dx+v.x,dz+v.z,dx+v.x,dz+v.z)) from (values(0.,0.),(-1.6,-1.0),(-1.6,1.0),(1.6,-1.0),(1.6,1.0))v(x,z)) then ok:=true;exit;end if;
  end loop;
  if not ok then raise notice 'Skilling world: no clear spot for % (%), skipped',row->>'name',row->>'key';continue;end if;
  if added=0 then update eldervale_private.settings set revision=revision+1 where id returning revision into rev;end if;
  d:='{"kind":"object","scale":1,"level":1,"hp":1,"damage":0,"attackSpeed":2.4,"roam":0,"respawn":0,"attackable":false,"hostile":false,"blueprint":"${SKILLING_BLUEPRINT}"}'::jsonb||(row-'id'-'key')||jsonb_build_object('skillingKey',row->>'key','x',round(dx::numeric,1),'z',round(dz::numeric,1));
  insert into eldervale_private.entities(id,revision,data) values((row->>'id')::uuid,rev,d) on conflict(id) do nothing;
  added:=added+1;
 end loop;
 raise notice 'Skilling world: % new nodes placed',added;
end $$;
`;
fs.writeFileSync(new URL('db/skilling-world.sql',root),sql);
console.log('db/skilling-world.sql',rows.length,'nodes');
