// Generates db/explore-2-content.sql and db/explore-3-clues.sql from explore-data.js.
// Usage: node scripts/build-explore-sql.mjs   (tests/explore.test.js checks the files are current)
import {writeFileSync} from 'node:fs';
import {ITEMS,DEFAULT_SETTINGS,AREAS,PLACES,LORE,CRATES,RESOURCES,SHORTCUTS,STEPS,REWARDS,validateExplore} from '../explore-data.js';

const json=v=>JSON.stringify(v);
// Dollar-quoted JSON literal (the tag never occurs in the content).
const lit=v=>{const s=json(v);if(s.includes('$j$'))throw Error('content contains $j$');return '$j$'+s+'$j$::jsonb'};
const defs=(kind,rows)=>`insert into eldervale_private.explore_defs(kind,id,data) select '${kind}',r->>'id',r-'id' from jsonb_array_elements(${lit(rows)}) r
 on conflict(kind,id) do update set data=excluded.data,updated_at=now() where not eldervale_private.explore_defs.owner_edited and eldervale_private.explore_defs.data is distinct from excluded.data;`;

export function buildContent(){
 const errors=validateExplore();if(errors.length)throw Error('explore-data.js: '+errors.join('; '));
 const catalog=Object.entries(ITEMS).map(([id,d])=>['item:'+id,{...d,unique:true,shopless:true,tradeable:d.kind==='keepsake',untradeable:d.kind!=='keepsake',explore:true}]);
 return `-- Eldervale exploration, part 2: settings, items, explore areas, places, lore, crates, resources, shortcuts.
-- Generated by scripts/build-explore-sql.mjs from explore-data.js. Do not edit by hand.
-- APPLY AFTER db/explore-1-core.sql. Idempotent:
--  * settings ('explore' in game_settings) and catalog items are only inserted when missing (owner changes stay);
--  * explore areas are refreshed unless saved from the Underground console (updated_by set);
--  * definitions are refreshed unless saved from the Exploration console (owner_edited);
--  * explore_sync() then writes every object as a world entity (fixed ids).
begin;
set local lock_timeout='5s';
insert into eldervale_private.game_settings(key,value,updated_at) values('explore',${lit(DEFAULT_SETTINGS)},now()) on conflict(key) do nothing;
insert into eldervale_private.realm_catalog(id,data) select r->>0,r->1 from jsonb_array_elements(${lit(catalog)}) r on conflict(id) do nothing;
do $areas$
declare a jsonb;
begin
 for a in select value from jsonb_array_elements(${lit(AREAS)}) loop
  insert into eldervale_private.underground_areas(id,data,enabled) values(a->>'id',a-'enabled',true)
   on conflict(id) do update set data=excluded.data,updated_at=now() where eldervale_private.underground_areas.updated_by is null and eldervale_private.underground_areas.data is distinct from excluded.data;
  perform eldervale_private.underground_sync(a->>'id');
 end loop;
end $areas$;
${defs('place',PLACES)}
${defs('lore',LORE)}
${defs('crate',CRATES)}
${defs('resource',RESOURCES)}
${defs('shortcut',SHORTCUTS.map(s=>({...s,x:0,z:0})))}
select eldervale_private.explore_sync();
commit;
`;
}
export function buildClues(){
 const rewards=Object.entries(REWARDS).map(([id,d])=>({id,...d}));
 return `-- Eldervale exploration, part 3: treasure-hunt clue steps (${STEPS.length}) and reward casket tables.
-- Generated by scripts/build-explore-sql.mjs from explore-data.js. Do not edit by hand.
-- APPLY AFTER db/explore-2-content.sql. Idempotent; rows saved from the Exploration console (owner_edited) are kept.
begin;
set local lock_timeout='5s';
${defs('step',STEPS)}
${defs('reward',rewards)}
select eldervale_private.explore_sync();
commit;
`;
}
if(import.meta.url===`file://${process.argv[1]}`){
 const root=new URL('..',import.meta.url).pathname;
 writeFileSync(root+'db/explore-2-content.sql',buildContent());
 writeFileSync(root+'db/explore-3-clues.sql',buildClues());
 console.log('wrote db/explore-2-content.sql and db/explore-3-clues.sql');
}
