// Builds db/birchford-capital.sql from capital-layout.js: the walled royal
// capital around Birchford (walls, gates, streets, buildings, shops, guards and
// townsfolk). Run: node scripts/build-capital-seed.mjs
import fs from 'node:fs';
import {capital,capitalBlueprint,capitalClearing,capitalZone,CAPITAL_BLUEPRINT} from '../capital-layout.js';
const fixture=JSON.parse(fs.readFileSync(new URL('../tests/fixtures/birchford-existing.json',import.meta.url)));
const rows=capitalBlueprint();
const poly='(('+capitalClearing.map(([x,z])=>x+','+z).join('),(')+'))';
const retired=fixture.retired.map(id=>`'${id}'`).join(',');
const json=JSON.stringify(rows);if(json.includes('$plan$'))throw Error('delimiter clash');
const sql=`-- Birchford, royal capital of Eldervale. Generated by scripts/build-capital-seed.mjs
-- from capital-layout.js (the same plan the client and tests use); do not edit by hand.
-- Apply AFTER db/general-store-and-fisherman.sql. Idempotent: every row is keyed by
-- blueprint '${CAPITAL_BLUEPRINT}' + blueprintKey and skipped when it already exists.
-- Adds: curtain wall with ${rows.filter(r=>r.template==='castle_tower').length} towers and ${capital.gates.length} held-open gates on the roads,
-- paved streets and lamps, the Keep, a temple, two banks, two guild halls (furnace,
-- anvil, workbench, spinning wheel), the Gilded Antler inn (cooking range), nine shops,
-- an eight-stall Grand Market, homes, gate wardens, wall patrols and townsfolk routines.
-- Shop prices come from realm_catalog (the seed stops if any stock item is missing).
-- Also: retires ${fixture.retired.length} dressing trees/rocks that stood in the new streets or walls,
-- disables the seeded forest trees inside the walls (as db/adventure-camp-seed.sql does
-- for the trail camp), and widens the Birchford town zone to the walled city.
do $seed$
declare rev bigint;r jsonb;d jsonb;shop jsonb;missing text;added integer:=0;
 plan jsonb:=$plan$${json}$plan$::jsonb;
begin
 select string_agg(distinct i,', ') into missing from jsonb_array_elements(plan) e(r) cross join lateral jsonb_array_elements_text(coalesce(e.r->'shopItems','[]'::jsonb)) i
  where not exists(select 1 from eldervale_private.realm_catalog c where c.id='item:'||i);
 if missing is not null then raise exception 'Capital stock missing from the catalog: %',missing;end if;
 update eldervale_private.settings set revision=revision+1 where id returning revision into rev;
 for r in select value from jsonb_array_elements(plan) loop
  if exists(select 1 from eldervale_private.entities where not deleted and data->>'blueprint'='${CAPITAL_BLUEPRINT}' and data->>'blueprintKey'=r->>'blueprintKey') then continue;end if;
  d:=r-'shopItems';
  if r ? 'shopItems' then
   select jsonb_object_agg(i,jsonb_build_object('buy',(c.data->>'buy')::integer,'sell',(c.data->>'sell')::integer,'stock',-1)) into shop
    from jsonb_array_elements_text(r->'shopItems') i join eldervale_private.realm_catalog c on c.id='item:'||i;
   d:=d||jsonb_build_object('shop',shop);
  end if;
  insert into eldervale_private.entities(id,revision,data) values(gen_random_uuid(),rev,d);added:=added+1;
 end loop;
 -- Dressing that stood where the walls, streets and doors now are.
 update eldervale_private.entities set deleted=true,revision=rev where not deleted and id::text in (${retired});
 -- The forest stops at the walls: seeded trees inside are never available (no collision, no chopping).
 update eldervale_private.realm_objects set available_at='infinity' where kind='tree' and id like 'base:tree:%' and point(x,z)<@polygon '${poly}' and available_at is distinct from 'infinity';
 -- Gates and business doors stand open.
 update eldervale_private.realm_objects o set open=true where not o.open and o.id in (select id::text from eldervale_private.entities where not deleted and data->>'blueprint'='${CAPITAL_BLUEPRINT}')
  and (o.kind='castle_gate' or (o.kind='door' and eldervale_private.door_held_open(o.id)));
 -- Town zone (sanctuary) covers the walled city.
 update eldervale_private.town_zones set x=${capitalZone.x},z=${capitalZone.z},radius=${capitalZone.half},square=true where id='Birchford';
 if added=0 then update eldervale_private.settings set revision=revision-1 where id;end if;
 raise notice 'Birchford capital: % entities added',added;
end $seed$;

-- Sanity report: counts by template, gates open, shops stocked.
select data->>'template' as template,count(*) from eldervale_private.entities where not deleted and data->>'blueprint'='${CAPITAL_BLUEPRINT}' group by 1 order by 1;
select e.data->>'name' as gate,o.open from eldervale_private.entities e join eldervale_private.realm_objects o on o.id=e.id::text where e.data->>'blueprint'='${CAPITAL_BLUEPRINT}' and e.data->>'template'='castle_gate' and not e.deleted;
select e.data->>'name' as merchant,(select count(*) from eldervale_private.shop_stock s where s.merchant=e.id::text) as stock_rows from eldervale_private.entities e where e.data->>'blueprint'='${CAPITAL_BLUEPRINT}' and e.data->>'template'='merchant' and not e.deleted order by 1;
`;
fs.writeFileSync(new URL('../db/birchford-capital.sql',import.meta.url),sql);
console.log('db/birchford-capital.sql',rows.length,'rows',(sql.length/1024).toFixed(1)+' KB');
