// Writes db/monster-roster.sql from monster-roster.js, monster-spawns.js and bestiary.js.
// usage: node --import ./tests/helpers/preload.js scripts/build-monster-roster-sql.mjs
import fs from 'node:fs';
import {rosterBeasts,BONES,ALTAR_OFFER_MULTIPLIER} from '../monster-roster.js';
import {monsterSpawns} from '../monster-spawns.js';
import {bestiaryEntity} from '../bestiary.js?v=release-20261106-perf90';
import {professionItems} from '../profession-data.js?v=release-20261106-perf90';
const root=new URL('../',import.meta.url);
export const BLUEPRINT='monster-roster-v1';
const pad=(n,w=12)=>String(n).padStart(w,'0');
export const entityId=i=>'b0e5a000-0000-4000-8000-'+pad(i+1);
const groups=[...new Set(monsterSpawns.map(s=>s.group))];
export const groupId=name=>'b0e5a000-0000-4000-9000-'+pad(groups.indexOf(name)+1);
export function rosterEntities(){return monsterSpawns.map((s,i)=>{const e=bestiaryEntity(s.key,s.x,s.z);return {id:entityId(i),data:{...e,yaw:s.yaw,behavior:'wander',group:groupId(s.group),groupName:s.group,rosterKey:s.key,blueprint:BLUEPRINT,blueprintKey:String(i+1)}}})}
const lootItems=[...new Set(Object.values(rosterBeasts).flatMap(b=>b.loot.map(l=>l.item)).concat(['ashes']))].sort();
const bonesCatalog=Object.keys(BONES).map(id=>{const {name,model,category,buy,sell,stackable,profession,color,prayerXP,description}=professionItems[id];return ['item:'+id,{name,model,category,buy,sell,stackable,profession,color,prayerXP,description,icon:'supply'}]});
const json=v=>{const t=JSON.stringify(v);if(t.includes('$j$'))throw Error('quote clash');return '$j$'+t+'$j$'};
const rows=rosterEntities();
const sql=`-- Generated by scripts/build-monster-roster-sql.mjs from monster-roster.js, monster-spawns.js
-- and bestiary.js. Do not edit by hand.
--
-- Eldervale monster roster: ${Object.keys(rosterBeasts).length} new monster types (levels 2-120) placed as ${rows.length} spawns in
-- ${groups.length} groups across the four regions, with OSRS-style stat blocks and loot tables, plus bones
-- for Prayer. APPLY AFTER db/osrs-equipment-combat.sql (the tier gear these monsters carry must
-- be in the catalog; this file stops with a clear error otherwise). Idempotent: safe to re-run.
--
-- * Catalog: Bones (${BONES.bones.xp} Prayer XP), Hefty bones (${BONES.heftyBones.xp}) and Wyrm bones (${BONES.wyrmBones.xp}).
-- * Command 'bury' (realm_request_services, through patch_function): buries one bone from the
--   inventory for its Prayer XP, or x${ALTAR_OFFER_MULTIPLIER} when standing within 4 m of an altar; shares the eating
--   delay (consume_at), so burying in combat costs a moment, as in OSRS.
-- * entity_runtime (patch_function): a monster keeps its own attack/strength/defence levels
--   (they used to be reset to its level) and levels may exceed 100 (bosses to 120).
-- * Entities: fixed ids b0e5a000-0000-4000-8000-..., blueprint '${BLUEPRINT}'. A row the owner has
--   marked deleted=true stays that way; rows of an older roster revision that are no longer
--   generated are marked deleted=true.
-- * Existing monsters gain an "always" bones row (hefty bones for trolls, ogres, bears and boars,
--   wyrm bones for dragons, ashes for demons and imps) when they have room for it (8 rows).
begin;

-- Bones (the bank-note trigger adds their notes).
insert into eldervale_private.realm_catalog(id,data)
select r->>0,r->1 from jsonb_array_elements(${json(bonesCatalog)}::jsonb) r
on conflict (id) do update set data=eldervale_private.realm_catalog.data||excluded.data
 where not coalesce(eldervale_private.realm_catalog.data ? 'ownerEdited',false) and eldervale_private.realm_catalog.data is distinct from eldervale_private.realm_catalog.data||excluded.data;

-- Every loot item must exist (tier gear comes from db/osrs-equipment-combat.sql).
do $check$
declare missing text;
begin
 select string_agg(i,', ' order by i) into missing from jsonb_array_elements_text(${json(lootItems)}::jsonb) i
  where not exists(select 1 from eldervale_private.realm_catalog c where c.id='item:'||i);
 if missing is not null then raise exception 'Monster roster loot items missing from the catalog (apply db/osrs-equipment-combat.sql first): %',missing;end if;
end $check$;

-- Monsters keep their own combat levels; levels up to 999 (bosses reach 120).
do $runtime$
declare body text:=pg_get_functiondef('eldervale_private.entity_runtime()'::regprocedure);
begin
 if position('coalesce((d->>''attackLevel'')::integer' in body)>0 then return;end if;
 perform eldervale_private.patch_function('eldervale_private.entity_runtime()'::regprocedure,array[
  $o$'level',greatest(1,least(100,coalesce((d->>'level')::integer,1))),'attackLevel',greatest(1,least(100,coalesce((d->>'level')::integer,1))),'defenceLevel',greatest(1,least(100,coalesce((d->>'level')::integer,1))),'strengthLevel',greatest(1,least(100,coalesce((d->>'level')::integer,1)))$o$,
  $n$'level',greatest(1,least(999,coalesce((d->>'level')::integer,1))),'attackLevel',greatest(1,least(999,coalesce((d->>'attackLevel')::integer,(d->>'level')::integer,1))),'defenceLevel',greatest(1,least(999,coalesce((d->>'defenceLevel')::integer,(d->>'level')::integer,1))),'strengthLevel',greatest(1,least(999,coalesce((d->>'strengthLevel')::integer,(d->>'level')::integer,1)))$n$]);
end $runtime$;

-- Bury (or offer at an altar) one bone for Prayer XP.
create or replace function eldervale_private.bury_bones(session_id uuid, payload jsonb, request_id uuid) returns void
language plpgsql security definer set search_path to '' as $f$
declare p eldervale_private.realm_players;c jsonb;k text;xp numeric;altar boolean;
begin
 if not eldervale_private.allowed() then raise exception 'Sign in required' using errcode='42501';end if;
 perform pg_advisory_xact_lock(736211);
 select * into p from eldervale_private.realm_players where user_id=auth.uid() and realm_players.session_id=$1 for update;
 if not found then raise exception 'Session expired';end if;
 if request_id is null then raise exception 'Request ID required';end if;
 if exists(select 1 from eldervale_private.realm_requests r where r.user_id=auth.uid() and r.request_id=$3) then return;end if;
 if payload is null or jsonb_typeof(payload)<>'object' or pg_column_size(payload)>500 then raise exception 'Invalid command';end if;
 if p.consume_at>clock_timestamp()-interval '1.1 seconds' then raise exception 'You are already busy.';end if;
 k:=payload->>'item';
 select data into c from eldervale_private.realm_catalog where id='item:'||k and not(data ? 'noteOf');
 if c is null or coalesce(jsonb_typeof(c->'prayerXP'),'')<>'number' or coalesce((c->>'prayerXP')::numeric,0)<=0 then raise exception 'You cannot bury that.';end if;
 if coalesce((select (s.stats->>k)::integer from public.player_saves s where s.user_id=auth.uid()),0)<1 then raise exception 'You have no % to bury.',lower(c->>'name');end if;
 perform eldervale_private.item_change(auth.uid(),k,-1);
 altar:=exists(select 1 from eldervale_private.realm_objects o where o.data->>'template'='altar' and coalesce((o.data->>'floor')::integer,0)=coalesce(p.floor,0) and sqrt(power(p.x-o.x,2)+power(p.z-o.z,2))<=4);
 xp:=(c->>'prayerXP')::numeric*(case when altar then ${ALTAR_OFFER_MULTIPLIER} else 1 end);
 perform eldervale_private.skill_xp(auth.uid(),'prayer',xp);
 update eldervale_private.realm_players set consume_at=clock_timestamp() where user_id=auth.uid();
 perform eldervale_private.emit(jsonb_build_object('type','notice','player',auth.uid(),'text',
  (case when altar then 'You offer the '||lower(c->>'name')||' at the altar.' else 'You bury the '||lower(c->>'name')||'.' end)||' +'||trim_scale(xp)::text||' Prayer XP.'));
 insert into eldervale_private.realm_requests(user_id,request_id,result) values(auth.uid(),request_id,'{}');
end $f$;
revoke all on function eldervale_private.bury_bones(uuid,jsonb,uuid) from public,anon,authenticated;

do $bury$
declare body text:=pg_get_functiondef('eldervale_private.realm_request_services(uuid,text,jsonb,uuid,bigint)'::regprocedure);
begin
 if position('bury_bones' in body)>0 then return;end if;
 perform eldervale_private.patch_function('eldervale_private.realm_request_services(uuid,text,jsonb,uuid,bigint)'::regprocedure,array[
  $o$if command in ('pray','cook') then$o$,
  $n$if command='bury' then
  perform eldervale_private.bury_bones($1,payload,request_id);
  result:=eldervale_private.realm_request_before_castle(session_id,'sync','{}',null,event_cursor);
 elsif command in ('pray','cook') then$n$]);
end $bury$;

-- Roster entities and bones for the existing monsters.
do $roster$
declare rev bigint;n integer:=0;k integer;e record;bone text;
begin
 update eldervale_private.settings set revision=revision+1 where id returning revision into rev;
 insert into eldervale_private.entities(id,revision,data)
 select v.id::uuid,rev,v.data from (values
${rows.map(r=>"  ('"+r.id+"',"+json(r.data)+'::jsonb)').join(',\n')}
 ) v(id,data)
 on conflict(id) do update set data=excluded.data,revision=excluded.revision
  where not eldervale_private.entities.deleted and eldervale_private.entities.data is distinct from excluded.data;
 get diagnostics k=row_count;n:=n+k;
 -- Older roster rows that are no longer generated (marked deleted=true).
 update eldervale_private.entities set deleted=true,revision=rev
  where not deleted and data->>'blueprint'='${BLUEPRINT}' and not (id::text = any(${"array["+rows.map(r=>"'"+r.id+"'").join(',')+"]"}));
 get diagnostics k=row_count;n:=n+k;
 for e in select x.id,x.data from eldervale_private.entities x where not x.deleted and x.data->>'kind'='monster' and coalesce(x.data->>'blueprint','') is distinct from '${BLUEPRINT}'
   and coalesce(x.data->>'species','') not in ('dummy','golem','wraith') and coalesce(x.data->>'template','') is distinct from 'training_dummy' loop
  bone:=case when e.data->>'species'='dragon' then 'wyrmBones' when e.data->>'species' in ('troll','ogre','bear','boar') then 'heftyBones' when e.data->>'species' in ('demon','imp') then 'ashes' else 'bones' end;
  if (jsonb_typeof(e.data->'loot') is distinct from 'array') then
   update eldervale_private.entities set data=data||jsonb_build_object('loot',jsonb_build_array(jsonb_build_object('item',bone,'min',1,'max',1,'chance',1,'always',true))),revision=rev where id=e.id;n:=n+1;
  elsif (jsonb_array_length(e.data->'loot')<8 and not exists(select 1 from jsonb_array_elements(e.data->'loot') l where l->>'item' in ('bones','heftyBones','wyrmBones','ashes'))) then
   update eldervale_private.entities set data=data||jsonb_build_object('loot',jsonb_build_array(jsonb_build_object('item',bone,'min',1,'max',1,'chance',1,'always',true))||(data->'loot')),revision=rev where id=e.id;n:=n+1;
  end if;
 end loop;
 if n=0 then update eldervale_private.settings set revision=revision-1 where id;end if;
 raise notice 'Monster roster: % entities added or updated',n;
end $roster$;

commit;
`;
for(const word of ['delete','alter','drop'])if(new RegExp('\\b'+word+'\\b','i').test(sql))throw Error('SQL must avoid the word '+word+': '+sql.match(new RegExp('.{0,60}\\b'+word+'\\b.{0,60}','i'))[0]);
fs.writeFileSync(new URL('db/monster-roster.sql',root),sql);
console.log('db/monster-roster.sql: '+rows.length+' entities, '+lootItems.length+' loot items, '+(sql.length/1024).toFixed(0)+' KiB');
