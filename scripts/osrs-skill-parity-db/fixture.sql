CREATE OR REPLACE FUNCTION eldervale_private.fish_catch(method text, level integer, roll double precision)
 RETURNS jsonb
 LANGUAGE plpgsql
 IMMUTABLE
 SET search_path TO ''
AS $function$
declare t jsonb;r float8:=greatest(0,least(.999999,coalesce(roll,0)));n integer;
begin
 select coalesce(jsonb_agg(f order by (f->>'level')::integer desc),'[]'::jsonb) into t from jsonb_array_elements(eldervale_private.fish_table()) f where f->>'method'=method and (f->>'level')::integer<=level;
 n:=jsonb_array_length(t);if n=0 then return null;end if;
 for i in 0..n-1 loop if i=n-1 or r<.55 then return t->i;end if;r:=(r-.55)/.45;end loop;
 return null;
end $function$;

CREATE OR REPLACE FUNCTION eldervale_private.combat_xp(uid uuid, damage integer, style text, w jsonb)
 RETURNS void
 LANGUAGE plpgsql
 SET search_path TO ''
AS $function$
declare d integer:=greatest(0,coalesce(damage,0));magic boolean:=coalesce((w->>'magic')::boolean,false);ranged boolean:=coalesce((w->>'ranged')::boolean,false);gains jsonb;third integer;
begin
 third:=round(4*d/3.0)::integer;
 gains:=case when magic then jsonb_build_object('magicXP',2*d+coalesce((w->>'spellXp')::integer,6))
  when ranged then jsonb_build_object('rangedXP',4*d)
  when style='stab' then jsonb_build_object('attackXP',4*d)
  when style='lunge' then jsonb_build_object('attackXP',third,'strengthXP',third,'defenceXP',third)
  else jsonb_build_object('strengthXP',4*d) end||jsonb_build_object('hitpointsXP',third);
 update public.player_saves set skills=skills||coalesce((select jsonb_object_agg(g.key,least(200000000,coalesce((skills->>g.key)::numeric,0)+g.value::numeric)) from jsonb_each_text(gains) g where g.value::numeric>0),'{}'::jsonb) where user_id=uid;
end $function$;

CREATE OR REPLACE FUNCTION eldervale_private.gathering_error_before_professions(uid uuid, target_id text, method text)
 RETURNS text
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
declare p eldervale_private.realm_players;s public.player_saves;o eldervale_private.realm_objects;
begin
 select * into p from eldervale_private.realm_players where user_id=uid;select * into s from public.player_saves where user_id=uid;
 if p.user_id is null or p.last_seen<clock_timestamp()-interval '15 seconds' or s.health<=0 then return 'Gathering stopped.';end if;
 if exists(select 1 from eldervale_private.moderation where user_id=uid and (banned_until>clock_timestamp() or kicked_at>p.last_seen)) then return 'Gathering stopped.';end if;
 if exists(select 1 from eldervale_private.realm_actors where target=uid and hp>0 and not deleted) then return 'Finish combat before gathering.';end if;
 select * into o from eldervale_private.realm_objects where id=target_id;
 if not found or o.kind<>(case when method='woodcut' then 'tree' else 'fishing' end) then return 'That resource is unavailable.';end if;
 if sqrt(power(o.x-p.x,2)+power(o.z-p.z,2))>(case when method='woodcut' then 3.5 else 4 end) then return 'Move closer to the resource.';end if;
 if o.available_at>clock_timestamp() then return 'This tree is regrowing.';end if;
 if method='woodcut' and not(coalesce(s.inventory->'weaponsOwned','[]')?'axe' or s.equipment->>'weapon'='axe') then return 'You need a woodcutting axe in your inventory or equipped.';end if;
 if method='rod' and coalesce((s.stats->>'fishingPole')::integer,0)<1 then return 'You need a fishing pole in your inventory.';end if;
 if method='rod' and coalesce((s.stats->>'bait')::integer,0)<1 then return 'You need fishing bait.';end if;
 if method='net' and coalesce((s.stats->>'fishingNet')::integer,0)<1 then return 'You need a fishing net in your inventory.';end if;
 if eldervale_private.inventory_used(uid)>=eldervale_private.inventory_capacity() and not(method='rod' and (s.stats->>'bait')::integer=1) then return 'Your inventory is full.';end if;
 return null;
end $function$;

CREATE OR REPLACE FUNCTION eldervale_private.gathering_error(uid uuid, target_id text, method text)
 RETURNS text
 LANGUAGE plpgsql
 SET search_path TO ''
AS $function$declare problem text;o eldervale_private.realm_objects;xp integer;required integer;begin
 problem:=eldervale_private.gathering_error_before_professions(uid,target_id,method);if problem is not null then return problem;end if;
 if method='woodcut' then select * into o from eldervale_private.realm_objects where id=target_id;required:=case o.data->>'logItem' when 'oakLogs' then 15 when 'willowLogs' then 30 when 'mapleLogs' then 45 when 'yewLogs' then 60 else 1 end;
 select coalesce((stats->>'woodXP')::integer,0) into xp from public.player_saves where user_id=uid;if eldervale_private.xp_level(xp)<required then return 'You need Woodcutting level '||required||' for this tree.';end if;end if;
 if method in('cage','harpoon') then
  select coalesce((skills->>'fishingXP')::numeric,0)::integer,coalesce((stats->>(case method when 'cage' then 'lobsterPot' else 'harpoon' end))::integer,0) into xp,required from public.player_saves where user_id=uid;
  if required<1 then return case method when 'cage' then 'You need a lobster pot in your inventory.' else 'You need a harpoon in your inventory.' end;end if;
  if eldervale_private.xp_level(xp)<(case method when 'cage' then 40 else 50 end) then return 'You need Fishing level '||(case method when 'cage' then '40 to catch lobsters.' else '50 to use a harpoon.' end);end if;
 end if;return null;
end $function$;

CREATE OR REPLACE FUNCTION eldervale_private.gathering_tick(t timestamp with time zone)
 RETURNS void
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
declare a eldervale_private.gathering_actions;o eldervale_private.realm_objects;problem text;remaining integer;n integer;capacity integer;respawn integer;delay float8;uid uuid;min_logs integer;max_logs integer;caught jsonb;
begin
 for a in select * from eldervale_private.gathering_actions where due_at<=t for update loop
  select user_id into uid from eldervale_private.realm_players where user_id=a.user_id and (input_until>t and (abs(input_x)+abs(input_z)>.001) or path<>'[]');
  problem:=case when uid is not null then 'Gathering stopped.' else eldervale_private.gathering_error(a.user_id,a.target,a.method) end;
  if problem is not null then delete from eldervale_private.gathering_actions where user_id=a.user_id;perform eldervale_private.emit(jsonb_build_object('type','gather_end','player',a.user_id,'text',problem));continue;end if;
  if a.due_at>t then continue;end if;
  select * into o from eldervale_private.realm_objects where id=a.target for update;
  capacity:=greatest(0,eldervale_private.inventory_capacity()-eldervale_private.inventory_used(a.user_id));
  if a.method='woodcut' then
   min_logs:=greatest(1,least(10,case when coalesce(o.data->>'resourceMinLogs','')~'^[0-9]{1,4}$' then (o.data->>'resourceMinLogs')::integer else 1 end));
   max_logs:=greatest(min_logs,least(10,case when coalesce(o.data->>'resourceMaxLogs','')~'^[0-9]{1,4}$' then (o.data->>'resourceMaxLogs')::integer else 5 end));
   remaining:=coalesce((o.data->>'logsRemaining')::integer,min_logs+floor(random()*(max_logs-min_logs+1))::integer);
   n:=least(remaining,capacity,case when random()<.15 then 2 else 1 end);
   if n<1 then continue;end if;
   perform eldervale_private.item_change(a.user_id,eldervale_private.tree_log_item(o.data),n);remaining:=remaining-n;
   update public.player_saves set stats=stats||jsonb_build_object('woodXP',coalesce((stats->>'woodXP')::integer,0)+eldervale_private.tree_log_xp(o.data)*n) where user_id=a.user_id;
   respawn:=greatest(15,least(3600,case when coalesce(o.data->>'resourceRespawn','')~'^[0-9]{1,4}$' then (o.data->>'resourceRespawn')::integer else 45 end));
   update eldervale_private.realm_objects set data=data||jsonb_build_object('logsRemaining',remaining),available_at=case when remaining=0 then t+make_interval(secs=>respawn) else null end where id=o.id;
   perform eldervale_private.emit(jsonb_build_object('type','woodcut','player',a.user_id,'target',o.id,'amount',n,'depleted',remaining=0,'availableAt',case when remaining=0 then t+make_interval(secs=>respawn) else null end));
   if remaining=0 then delete from eldervale_private.gathering_actions where user_id=a.user_id;continue;end if;delay:=3.0;
  else
   if a.method='rod' then perform eldervale_private.item_change(a.user_id,'bait',-1);end if;
   -- One catch per cycle; nets require no bait.
   caught:=eldervale_private.fish_catch(a.method,eldervale_private.xp_level((select (skills->>'fishingXP')::numeric from public.player_saves where user_id=a.user_id)),random());
   if caught is null then delete from eldervale_private.gathering_actions where user_id=a.user_id;perform eldervale_private.emit(jsonb_build_object('type','gather_end','player',a.user_id,'text','Your Fishing level is too low for this method.'));continue;end if;
   perform eldervale_private.item_change(a.user_id,caught->>'item',1);perform eldervale_private.skill_xp(a.user_id,'fishing',(caught->>'xp')::integer);
   perform eldervale_private.emit(jsonb_build_object('type','fishing','player',a.user_id,'target',o.id,'method',a.method,'amount',1,'item',caught->>'item','xp',(caught->>'xp')::integer));delay:=case when a.method='net' then 4.5 when a.method='cage' then 5 when a.method='harpoon' then 5.4 else 4 end;
  end if;
  problem:=eldervale_private.gathering_error(a.user_id,a.target,a.method);if problem is not null then delete from eldervale_private.gathering_actions where user_id=a.user_id;perform eldervale_private.emit(jsonb_build_object('type','gather_end','player',a.user_id,'text',problem));continue;end if;
  update eldervale_private.gathering_actions set started_at=t,due_at=t+make_interval(secs=>delay) where user_id=a.user_id;
 end loop;
 update eldervale_private.realm_objects set available_at=null,data=data-'logsRemaining' where kind='tree' and available_at<=t;
end $function$;

CREATE OR REPLACE FUNCTION eldervale_private.skill_error_before_notes(uid uuid, r jsonb, target_id text, drop_id uuid DEFAULT NULL::uuid)
 RETURNS text
 LANGUAGE plpgsql
 SET search_path TO ''
AS $function$
declare p eldervale_private.realm_players;s public.player_saves;o eldervale_private.realm_objects;d eldervale_private.ground_drops;k text;v jsonb;xp integer;level integer;station text;kind text;f eldervale_private.skill_fires;
begin
 select * into p from eldervale_private.realm_players where user_id=uid;select * into s from public.player_saves where user_id=uid;
 if p.user_id is null or p.last_seen<clock_timestamp()-interval '15 seconds' or s.health<=0 then return 'Activity stopped: reconnect to the world.';end if;
 if exists(select 1 from eldervale_private.moderation where user_id=uid and (banned_until>clock_timestamp() or kicked_at>p.last_seen)) then return 'Activity stopped.';end if;
 if exists(select 1 from eldervale_private.realm_actors where target=uid and hp>0 and not deleted) then return 'Finish combat before skilling.';end if;
 if not coalesce((r->>'enabled')::boolean,false) then return 'This recipe is disabled.';end if;
 xp:=coalesce((case when r->>'skill'='mining' then s.stats->>'miningXP' when r->>'skill'='woodcutting' then s.stats->>'woodXP' else s.skills->>((r->>'skill')||'XP') end)::integer,0);level:=eldervale_private.xp_level(xp);
 if level<(r->>'level')::integer then return 'You need '||(r->>'skill')||' level '||(r->>'level')||'.';end if;
 for k in select jsonb_array_elements_text(r->'tools') loop if not eldervale_private.skill_tool(uid,k) then return 'Required tool: '||k||'.';end if;end loop;
 kind:=r->>'kind';station:=r->>'station';
 if drop_id is not null then
  select * into d from eldervale_private.ground_drops where id=drop_id;
  if kind<>'fire' or d.id is null or d.expires_at<=clock_timestamp() or not((r->'inputs')?d.item) or d.amount<1 then return 'Those dropped logs are no longer available.';end if;
  if sqrt(power(d.x-p.x,2)+power(d.z-p.z,2))>3 then return 'Move within reach of the dropped logs.';end if;
 else
  for k,v in select key,value from jsonb_each(r->'inputs') loop if coalesce(eldervale_private.item_quantity(uid,k),0)<v::integer then return 'Not enough '||k||'.';end if;end loop;
 end if;
 if station is not null then
  if station='cooking' and target_id like 'fire:%' then
   select * into f from eldervale_private.skill_fires where id=substring(target_id from 6)::uuid and expires_at>clock_timestamp();
   if f.id is null or sqrt(power(f.x-p.x,2)+power(f.z-p.z,2))>4 then return 'Move closer to a burning fire.';end if;
  else
   select * into o from eldervale_private.realm_objects where id=target_id;
   if o.id is null then return 'Choose a nearby station in the world.';end if;
   if sqrt(power(o.x-p.x,2)+power(o.z-p.z,2))>4 then return 'Move closer to the station.';end if;
   if not(case station when 'mining_rock' then o.kind='rock' and coalesce(o.data->>'resource','ore')=r->>'resource' when 'cooking' then coalesce(o.data->>'template',o.data->>'type') in('hearth','campfire','cooking_tripod') when 'water' then coalesce(o.data->>'template',o.data->>'type') in('well','fountain') else coalesce(o.data->>'template',o.data->>'type')=station end) then return 'This is the wrong station.';end if;
   if kind='mine' and o.available_at>clock_timestamp() then return 'This resource is depleted. It will replenish shortly.';end if;
   if kind='plant' and exists(select 1 from eldervale_private.skill_crops where target=target_id) then return 'This patch already contains a crop.';end if;
   if kind='build' and coalesce((o.data->>'built')::boolean,false) then return 'This site is already built. The owner can reset or place another site.';end if;
  end if;
 end if;
 if kind='fire' then
  if drop_id is null then d.x:=p.x;d.z:=p.z;end if;
  if not eldervale_private.can_step(d.x,d.z,d.x,d.z) or exists(select 1 from eldervale_private.realm_objects b where b.kind='door' and sqrt(power(b.x-d.x,2)+power(b.z-d.z,2))<8*coalesce((b.data->>'scale')::float8,1)) then return 'Light fires on clear ground outside buildings.';end if;
  if exists(select 1 from eldervale_private.skill_fires where expires_at>clock_timestamp() and sqrt(power(x-d.x,2)+power(z-d.z,2))<1.5) then return 'There is already a fire here.';end if;
 end if;
 return null;
end $function$;

CREATE OR REPLACE FUNCTION eldervale_private.skill_error(uid uuid, r jsonb, target_id text, drop_id uuid DEFAULT NULL::uuid)
 RETURNS text
 LANGUAGE plpgsql
 SET search_path TO ''
AS $function$declare k text;begin
 for k in select key from jsonb_each(coalesce(r->'inputs','{}')) union select jsonb_array_elements_text(coalesce(r->'tools','[]')) loop if k like 'note:%' then return 'Bank notes cannot be used in skills. Exchange them at a bank first.';end if;end loop;
 return eldervale_private.skill_error_before_notes(uid,r,target_id,drop_id);
end $function$;

CREATE OR REPLACE FUNCTION eldervale_private.skill_finish(uid uuid, r jsonb, target_id text, drop_id uuid, t timestamp with time zone)
 RETURNS text
 LANGUAGE plpgsql
 SET search_path TO ''
AS $function$
declare problem text;k text;v jsonb;p eldervale_private.realm_players;o eldervale_private.realm_objects;d eldervale_private.ground_drops;failed boolean;kind text;points integer;result text;level integer;
begin
 -- Caller holds the world lock; resource rows and character are locked together.
 perform 1 from public.player_saves where user_id=uid for update;perform 1 from eldervale_private.realm_objects where id=target_id for update;
 if drop_id is not null then perform 1 from eldervale_private.ground_drops where id=drop_id for update;end if;
 problem:=eldervale_private.skill_error(uid,r,target_id,drop_id);if problem is not null then raise exception '%',problem;end if;
 select * into p from eldervale_private.realm_players where user_id=uid;kind:=r->>'kind';
 if drop_id is not null then select * into d from eldervale_private.ground_drops where id=drop_id;if d.amount=1 then delete from eldervale_private.ground_drops where id=drop_id;else update eldervale_private.ground_drops set amount=amount-1 where id=drop_id;end if;
 else for k,v in select key,value from jsonb_each(r->'inputs') loop perform eldervale_private.item_change(uid,k,-(v::integer));end loop;end if;
 if kind='fire' and coalesce(eldervale_private.item_quantity(uid,'tinderbox'),0)=0 then perform eldervale_private.item_change(uid,'matches',-1);end if;
 failed:=random()>coalesce((r->>'chance')::float8,1);
 if r?'burnChance' then
  select eldervale_private.xp_level((skills->>'cookingXP')::numeric) into level from public.player_saves where user_id=uid;
  failed:=(r->>'burnChance')::float8>0 and random()<greatest(.01,(r->>'burnChance')::float8*(1-least(1,greatest(0,level-coalesce((r->>'level')::integer,1))/35.0)));if failed then perform eldervale_private.item_change(uid,'burntFood',1);end if;
 end if;
 if not failed then
  for k,v in select key,value from jsonb_each(r->'outputs') loop perform eldervale_private.item_change(uid,k,v::integer);end loop;
  if kind='mine' then update eldervale_private.realm_objects set available_at=t+make_interval(secs=>(r->>'respawn')::float8) where id=target_id;
  elsif kind='fire' then insert into eldervale_private.skill_fires(owner_id,x,z,expires_at) values(uid,coalesce(d.x,p.x),coalesce(d.z,p.z),t+make_interval(secs=>coalesce((r->>'fireSeconds')::integer,90)));
  elsif kind='plant' then insert into eldervale_private.skill_crops(target,owner_id,item,amount,xp,ready_at) values(target_id,uid,r->'crop'->>'item',(r->'crop'->>'min')::integer+floor(random()*((r->'crop'->>'max')::integer-(r->'crop'->>'min')::integer+1))::integer,(r->'crop'->>'xp')::integer,t+make_interval(secs=>(r->'crop'->>'seconds')::float8));
  elsif kind='build' then update eldervale_private.realm_objects set data=data||'{"built":true}' where id=target_id;update eldervale_private.settings set revision=revision+1 where id;update eldervale_private.entities set data=data||'{"built":true}',revision=(select revision from eldervale_private.settings where id) where id::text=target_id;
  end if;
  points:=(r->>'xp')::integer;perform eldervale_private.skill_xp(uid,r->>'skill',points);result:=(r->>'name')||' complete. +'||points||' '||(r->>'skill')||' XP';
 else result:=case when r?'burnChance' then 'The food burns. Higher Cooking reduces the chance.' else 'The attempt failed. Try again.' end;end if;
 if eldervale_private.inventory_used(uid)>eldervale_private.inventory_capacity() then raise exception 'Inventory full. Free space before continuing.';end if;
 return result;
end $function$;

CREATE OR REPLACE FUNCTION eldervale_private.skill_tick(t timestamp with time zone)
 RETURNS void
 LANGUAGE plpgsql
 SET search_path TO ''
AS $function$
declare j eldervale_private.skill_jobs;r jsonb;problem text;f eldervale_private.skill_fires;
begin
 for j in select * from eldervale_private.skill_jobs where due_at<=t for update loop
  select data into r from eldervale_private.skill_recipes where id=j.recipe;
  if exists(select 1 from eldervale_private.realm_players where user_id=j.user_id and (path<>'[]' or input_until>t and abs(input_x)+abs(input_z)>.001)) then problem:='You stop skilling to move.';
  else
   problem:=null;
   begin
    perform eldervale_private.emit(jsonb_build_object('type','skill_complete','player',j.user_id,'text',eldervale_private.skill_finish(j.user_id,r,j.target,j.ground_drop,t)));
   exception when others then problem:=sqlerrm;end;
  end if;
  if problem is not null or j.remaining=1 then
   delete from eldervale_private.skill_jobs where user_id=j.user_id;if problem is not null then perform eldervale_private.emit(jsonb_build_object('type','skill_notice','player',j.user_id,'text',problem));end if;
  else update eldervale_private.skill_jobs set remaining=remaining-1,started_at=t,due_at=t+make_interval(secs=>(r->>'seconds')::float8) where user_id=j.user_id;end if;
 end loop;
 delete from eldervale_private.ground_drops where expires_at<=t;
 for f in select * from eldervale_private.skill_fires where expires_at<=t for update loop
  insert into eldervale_private.ground_drops(owner_id,item,amount,x,z) values(f.owner_id,'ashes',1,f.x,f.z);delete from eldervale_private.skill_fires where id=f.id;
 end loop;
end $function$;

