// Builds db/town-life.sql (server routes and town props for the seeded
// settlements) from town-routines.js and keeps db/generated-world.json, used
// by the offline browser checks, in step with it.
//   node scripts/build-town-life.mjs            write both files
//   node scripts/build-town-life.mjs --segments print route legs as JSON (for the server walk check)
import fs from 'node:fs';
import {planTownLife} from '../town-routines.js';
import {entityDefaults} from '../world-templates.js';
const file='db/generated-world.json',world=JSON.parse(fs.readFileSync(file));
const seed=world.config.seed,GEN='town-life-v1';
// Start from the seeded entities only, so the script can be re-run.
let entities=world.entities.filter(e=>e.generation!==GEN);
const titles={sweep:'Sweeper',carry:'Porter',garden:'Gardener',read:'Scribe'};
const updates=[],props=[],segments=[];
for(const town of world.towns){
 const plan=planTownLife(town,entities);
 const villagers=entities.filter(e=>e.template==='villager'&&e.generation==='seeded-world-v2'&&Math.hypot(e.x-town.x,e.z-town.z)<30).sort((a,b)=>a.generatedKey-b.generatedKey);
 const guards=entities.filter(e=>e.template==='guard'&&e.generation==='seeded-world-v2'&&Math.hypot(e.x-town.x,e.z-town.z)<45).sort((a,b)=>a.generatedKey-b.generatedKey);
 const counts={};
 villagers.forEach(v=>{const i=counts[v.activity]=(counts[v.activity]??-1)+1,route=plan.routeFor(v.activity,i);updates.push({key:v.generatedKey,patch:{route,x:route[0].x,z:route[0].z,name:v.name.replace(/ the .*/,' the '+(titles[v.activity]||'Scribe'))}})});
 guards.forEach((g,i)=>{const route=plan.guardRoute(i);updates.push({key:g.generatedKey,patch:{route,x:route[0].x,z:route[0].z}})});
 plan.props.forEach(p=>props.push({...entityDefaults(p.template,p.x,p.z),name:p.name,yaw:p.yaw,generation:GEN,seed,town:town.name}));
 for(const u of updates.slice(-villagers.length-guards.length)){const r=u.patch.route;r.forEach((s,i)=>{const n=r[(i+1)%r.length];segments.push({key:u.key,town:town.name,i,ax:s.x,az:s.z,bx:n.x,bz:n.z})})}
}
if(process.argv.includes('--segments')){console.log(JSON.stringify({segments,props}));process.exit(0)}
const json=v=>"'"+JSON.stringify(v).replace(/'/g,"''")+"'::jsonb";
const plan={routes:Object.fromEntries(updates.map(u=>[u.key,{...(u.patch.name?{n:u.patch.name}:{}),r:u.patch.route.map(s=>{const row=[s.x,s.z,s.wait,s.act??null,s.face??null,s.hold??null];while(row.length>3&&row[row.length-1]===null)row.pop();return row})}])),props:props.map(p=>[p.template,p.x,p.z,p.yaw,p.name,p.town])};
const sql=[`-- Town life: daily routines for the seeded townsfolk and the benches,
-- barrels and crates they work at. Generated by scripts/build-town-life.mjs
-- from town-routines.js; re-running replaces the previous town-life props.
-- 1. Actors remember which stop of their routine they are walking to.
alter table eldervale_private.realm_actors add column if not exists route_step integer;
-- 2. world_tick: a data.route loop takes precedence over random roaming, and
--    each stop's wait replaces the random roaming pause. Guarded in place.
do $$declare definition text;
 old1 text:=$o$   if coalesce((a.data->>'roam')::float8,0)>0 then
    if a.roam_pause_until>t then continue;end if;$o$;
 new1 text:=$n$   if jsonb_typeof(a.data->'route')='array' and jsonb_array_length(a.data->'route')>1 then
    if a.roam_pause_until>t then continue;end if;
    if a.roam_x is null then
     a.route_step:=(coalesce(a.route_step,-1)+1)%jsonb_array_length(a.data->'route');gx:=(a.data->'route'->a.route_step->>'x')::float8;gz:=(a.data->'route'->a.route_step->>'z')::float8;
     update eldervale_private.realm_actors set roam_x=gx,roam_z=gz,route_step=a.route_step where id=a.id;
    else gx:=a.roam_x;gz:=a.roam_z;end if;
   elsif coalesce((a.data->>'roam')::float8,0)>0 then
    if a.roam_pause_until>t then continue;end if;$n$;
 old2 text:=$o$roam_pause_until=t+(2+random()*3)*interval '1 second' where id=a.id;$o$;
 new2 text:=$n$roam_pause_until=t+(case when jsonb_typeof(a.data->'route')='array' then greatest(0,least(120,coalesce((a.data->'route'->coalesce(a.route_step,0)->>'wait')::float8,0))) else 2+random()*3 end)*interval '1 second' where id=a.id;$n$;
begin
 definition:=pg_get_functiondef('eldervale_private.world_tick()'::regprocedure);
 if strpos(definition,'a.data->''route''')>0 then raise notice 'world_tick already follows routes';
 else
  if (length(definition)-length(replace(definition,old1,'')))/length(old1)<>1 then raise exception 'Expected roaming block not found exactly once';end if;
  if (length(definition)-length(replace(definition,old2,'')))/length(old2)<>1 then raise exception 'Expected roaming pause not found exactly once';end if;
  execute replace(replace(definition,old1,new1),old2,new2);
 end if;
end $$;
-- 3. Routes, start points and job titles; town props with server collision.
--    Compact plan: routes[key]={n:name,r:[[x,z,wait,act,face,hold],...]},
--    props=[[template,x,z,yaw,name,town],...].
do $$declare rev bigint;k text;v jsonb;route jsonb;p jsonb;plan jsonb:=${json(plan)};begin
 update eldervale_private.settings set revision=revision+1 where id returning revision into rev;
 update eldervale_private.entities set deleted=true,revision=rev where data->>'generation'='${GEN}' and not deleted;
 for k,v in select * from jsonb_each(plan->'routes') loop
  select jsonb_agg(jsonb_strip_nulls(jsonb_build_object('x',s->0,'z',s->1,'wait',s->2,'act',s->3,'face',s->4,'hold',s->5)) order by ord) into route from jsonb_array_elements(v->'r') with ordinality e(s,ord);
  update eldervale_private.entities set data=data||jsonb_strip_nulls(jsonb_build_object('route',route,'x',route->0->'x','z',route->0->'z','name',v->'n')),revision=rev where not deleted and data->>'generation'='seeded-world-v2' and data->>'seed'='${seed}' and data->>'generatedKey'=k;
  if not found then raise exception 'Seeded actor % not found',k;end if;
 end loop;
 for p in select value from jsonb_array_elements(plan->'props') loop
  insert into eldervale_private.entities(revision,data) values(rev,jsonb_build_object('kind','object','name',p->4,'scale',1,'level',1,'hp',1,'damage',0,'attackSpeed',2.4,'roam',0,'respawn',0,'attackable',false,'hostile',false,'template',p->0,'x',p->1,'z',p->2,'yaw',p->3,'generation','${GEN}','seed',${seed},'town',p->5));
 end loop;
 update eldervale_private.realm_actors set route_step=null,roam_x=null,roam_z=null,roam_pause_until=null where jsonb_typeof(data->'route')='array';
end $$;
`];
fs.writeFileSync('db/town-life.sql',sql.join('\n'));
// Offline manifest mirrors the server data.
for(const u of updates){const e=entities.find(e=>e.generatedKey===u.key);Object.assign(e,u.patch)}
world.entities=[...entities,...props.map((p,i)=>({...p,generatedKey:'town-life-'+(i+1)}))];
fs.writeFileSync(file,JSON.stringify(world));
console.log(JSON.stringify({routes:updates.length,props:props.length,stops:updates.reduce((n,u)=>n+u.patch.route.length,0)}));
